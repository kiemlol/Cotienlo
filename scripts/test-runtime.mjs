import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const data=JSON.parse(await readFile('dist/data/game.json','utf8'));
const dictionary=JSON.parse(await readFile('dist/data/text_vi.json','utf8'));
const storage=new Map();
globalThis.localStorage={getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v)};
globalThis.location={href:'http://localhost/'};
globalThis.window={fetch:async p=>Response.json(p.includes('text_vi')?dictionary:data),addEventListener:()=>{},CTL:{zone:id=>data.zones[id],physics:p=>({state:{x:p.x,y:p.y},apply(i){this.state.x+=i.dx*.25;this.state.y+=i.dy*.25}})}};
